package it.giallotouch.bridge

/**
 * Strumenti chiave (non si possono gettare e il gioco non ne mostra la quantità), stessa tabella del gioco:
 * mappa, bicicletta, Pokédex, medaglie, fossili, biglietti, canne da pesca… e tutte le macchine nascoste (MN).
 */
object Items {
    private val KEY_ITEMS = setOf(
        0x05, 0x06, 0x07, 0x08, 0x09,
        0x15, 0x16, 0x17, 0x18, 0x19, 0x1A, 0x1B, 0x1C,
        0x1F, 0x29, 0x2A, 0x2B, 0x2C, 0x2D, 0x30, 0x3F, 0x40,
        0x45, 0x46, 0x47, 0x48, 0x49, 0x4A, 0x4C, 0x4D, 0x4E,
    )

    fun isKeyItem(id: Int): Boolean = id in KEY_ITEMS || id in MemoryMapIt.HM01 until MemoryMapIt.TM01

    /**
     * Strumenti che il gioco usa su un Pokémon della squadra (cure, pietre, vitamine, Caramella Rara, MT/MN): dopo USA
     * il gioco chiede su chi. Etere e PP-su scelgono poi anche la mossa (riquadro dell'app, D-093); gli Elisir valgono per tutte.
     */
    private val ON_POKEMON = setOf(
        0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F, 0x10, 0x11, 0x12, 0x13, 0x14,
        0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28, 0x2F, 0x34, 0x35, 0x36, 0x3C, 0x3D, 0x3E,
        0x4F, 0x50, 0x51, 0x52, 0x53,
    )

    fun usedOnPokemon(id: Int): Boolean = id in ON_POKEMON || id >= MemoryMapIt.HM01
}
